// Copies the WyrmVault ABI from the Foundry build output into src/chain/abi.ts.
// Run after `forge build` in contracts/: `pnpm --filter @wyrmhaven/server exec tsx scripts/sync-abi.ts`
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const artifact = join(here, '..', '..', '..', 'contracts', 'out', 'WyrmVault.sol', 'WyrmVault.json')
const { abi } = JSON.parse(readFileSync(artifact, 'utf8')) as { abi: unknown[] }
const out = `// Generated by scripts/sync-abi.ts from contracts/out/WyrmVault.sol/WyrmVault.json. Do not edit.
export const wyrmVaultAbi = ${JSON.stringify(abi, null, 2)} as const
`
writeFileSync(join(here, '..', 'src', 'chain', 'abi.ts'), out)
console.log(`wrote src/chain/abi.ts (${abi.length} entries)`)
