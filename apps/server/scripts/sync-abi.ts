// Copies the DrisVault ABI from the Foundry build output into apps/server/src/chain/abi.ts and
// packages/shared/src/abi.ts (the web client reads the shared copy).
// Run after `forge build` in contracts/: `pnpm --filter @wyrmhaven/server exec tsx scripts/sync-abi.ts`
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..', '..', '..')
const artifact = join(root, 'contracts', 'out', 'DrisVault.sol', 'DrisVault.json')
const { abi } = JSON.parse(readFileSync(artifact, 'utf8')) as { abi: unknown[] }

const erc20 = [
  { type: 'function', name: 'balanceOf', stateMutability: 'view', inputs: [{ name: 'account', type: 'address' }], outputs: [{ name: '', type: 'uint256' }] },
  { type: 'function', name: 'allowance', stateMutability: 'view', inputs: [{ name: 'owner', type: 'address' }, { name: 'spender', type: 'address' }], outputs: [{ name: '', type: 'uint256' }] },
  { type: 'function', name: 'approve', stateMutability: 'nonpayable', inputs: [{ name: 'spender', type: 'address' }, { name: 'value', type: 'uint256' }], outputs: [{ name: '', type: 'bool' }] },
  { type: 'function', name: 'decimals', stateMutability: 'view', inputs: [], outputs: [{ name: '', type: 'uint8' }] },
]

const header = '// Generated by apps/server/scripts/sync-abi.ts from contracts/out/DrisVault.sol/DrisVault.json. Do not edit.\n'
const vaultTs = `${header}export const drisVaultAbi = ${JSON.stringify(abi, null, 2)} as const\n`
writeFileSync(join(here, '..', 'src', 'chain', 'abi.ts'), vaultTs)
writeFileSync(
  join(root, 'packages', 'shared', 'src', 'abi.ts'),
  `${vaultTs}\n/** The subset of ERC-20 the client needs for deposits. */\nexport const erc20Abi = ${JSON.stringify(erc20, null, 2)} as const\n`,
)
console.log(`wrote server and shared abi.ts (${abi.length} vault entries)`)
